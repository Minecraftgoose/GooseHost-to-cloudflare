export function isFallbackDisposable(email) {
  const domain = String(email || '').split('@')[1] || '';
  if (!domain) return false;
  if (FALLBACK_DISPOSABLE.has(domain.toLowerCase())) return true;
  let dot = domain.indexOf('.');
  while (dot >= 0) {
    if (FALLBACK_DISPOSABLE.has(domain.slice(dot + 1).toLowerCase())) return true;
    dot = domain.indexOf('.', dot + 1);
  }
  return false;
}
